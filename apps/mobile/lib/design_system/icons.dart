class _EatMeIconPainter extends CustomPainter {
  const _EatMeIconPainter(this.glyph, this.color, this.strokeWidth);

  final EatMeGlyph glyph;
  final Color color;
  final double strokeWidth;

  @override
  void paint(Canvas canvas, Size size) {
    final scale = size.shortestSide / 24;
    canvas.save();
    canvas.translate((size.width - 24 * scale) / 2, (size.height - 24 * scale) / 2);
    canvas.scale(scale);
    final path = Path();
    for (final command in _paths[glyph]!) {
      switch (command[0].toInt()) {
        case 0:
          path.moveTo(command[1], command[2]);
        case 1:
          path.lineTo(command[1], command[2]);
        case 2:
          path.cubicTo(
            command[1],
            command[2],
            command[3],
            command[4],
            command[5],
            command[6],
          );
        case 3:
          path.close();
        case 4:
          path.quadraticBezierTo(command[1], command[2], command[1], command[2]);
      }
    }
    canvas.drawPath(
      path,
      Paint()
        ..color = color
        ..style = PaintingStyle.stroke
        ..strokeWidth = strokeWidth
        ..strokeCap = StrokeCap.round
        ..strokeJoin = StrokeJoin.round,
    );
    canvas.restore();
  }

