/// Renders Lucide geometry with a consistent rounded 24-point stroke.
class EatMeIcon extends StatelessWidget {
  const EatMeIcon(
    this.glyph, {
    super.key,
    this.size = 24,
    this.color,
    this.strokeWidth = 1.9,
  });

  final EatMeGlyph glyph;
  final double size;
  final Color? color;
  final double strokeWidth;

  @override
  Widget build(BuildContext context) => ExcludeSemantics(
    child: CustomPaint(
      size: Size.square(size),
      painter: _EatMeIconPainter(
        glyph,
        color ?? IconTheme.of(context).color ?? Theme.of(context).colorScheme.onSurface,
        strokeWidth,
      ),
    ),
  );
}

